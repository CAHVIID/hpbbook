"""Stratified hot water tank charged by a heat pump through an external heat exchanger.

This is the reference model behind the interactive app in the domestic hot water chapter
(dhw-tank.mjs runs the same model in the browser).

Layout:
- The tank is split into N horizontal layers of equal volume (layer 0 at the top).
- Charging loop: a pump draws water from the bottom of the tank, the heat exchanger heats it,
  and it returns to the layer at mid-height (inlet height adjustable).
- Tapping: hot water leaves at the top, and the same flow of cold mains water enters at the bottom.
  A thermostatic mixer at the tap mixes hot and cold water to the use temperature.
  If the top of the tank is colder than the use temperature, the tap gets tank water as it is.
- No circulation loop.

Physics per layer (explicit Euler, time step DT):
- Advection between layers with upwind differencing. The net flow across an interface is
  the tapping flow (upwards) minus the charging flow (downwards, only below the inlet).
- Vertical conduction with an effective conductivity (water plus tank wall).
- Heat loss to the room through UA, shared between layers by volume.
- Buoyancy: if a layer is warmer than the layer above it, the two are mixed. This is
  repeated until the tank is stable, so hot water entering at mid-height rises to its own level.

Heat pump and heat exchanger:
- The heat pump delivers its rated heat output, unless that would push its supply temperature
  above the maximum. The heat exchanger has a fixed approach: the water returned to the tank is
  `hex_approach` K colder than the heat pump supply.
- COP = eta_carnot * T_cond / (T_cond - T_evap), with T_cond = heat pump supply + 5 K
  and T_evap = source (outdoor air) temperature - 5 K.

Control:
- The heat pump starts when the sensor layer is below setpoint - hysteresis and stops when it
  reaches the setpoint. It also stops (high-temperature cut-out) when the water from the bottom
  of the tank is within 1 K of the highest temperature the heat exchanger can deliver.
  It only runs in the allowed hours.

Run:  python dhw_tank.py
"""
