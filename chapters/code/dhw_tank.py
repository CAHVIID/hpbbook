def tap_demand(t_day, p, profile=PROFILE):
    """Mean flow at the tap (L/s) over the time step starting at t_day (h), and its use temperature.
    Only the part of a tapping that falls inside the step counts, so every tapping has its exact volume.
    Tappings that share a step are added, with a flow-weighted use temperature."""
    step_h = DT / 3600
    f_sum = ft_sum = 0.0
    for start, _, vol, flow, temp in profile:
        vol *= p["use_scale"] / 100
        end = start + vol / flow / 60    # h
        overlap = min(t_day + step_h, end) - max(t_day, start)
        if overlap > 0:
            f = flow / 60 * overlap / step_h
            f_sum += f
            ft_sum += f * temp
    return (f_sum, ft_sum / f_sum) if f_sum > 0 else (0.0, None)


def load_dhwcalc(path, day=None, t_use=45.0):
    """Read a DHWcalc output file and return one day as a tapping profile, plus the file data.

    DHWcalc (Jordan & Vajen, Uni Kassel) writes one value per line: the draw-off flow in L/h for
    each time step, for a whole year (365 or 366 days) or one day. The time step follows from the
    number of lines. DHWcalc volumes carry no temperature; t_use is the draw-off temperature
    (45 C in IEA SHC Task 26). day is 0-based; None picks the day with the median volume."""
    flows = []
    for line in open(path):
        t = line.strip()
        if not t:
            continue
        try:
            flows.append(max(0.0, float(t.replace(";", " ").split()[-1].replace(",", "."))))
        except ValueError:
            pass
    n = len(flows)
    for days in (365, 366, 1):
        if n % days == 0 and abs(1440 / (n / days) - round(1440 / (n / days))) < 1e-9:
            spd, step_min = n // days, round(1440 / (n // days))
            break
    else:
        raise ValueError(f"{n} values: expected one flow value (L/h) per time step for 365 days or one day")
    daily = [sum(flows[d * spd:(d + 1) * spd]) * step_min / 60 for d in range(days)]
    if day is None:
        day = sorted(range(days), key=lambda d: daily[d])[days // 2]
    step_h = step_min / 60
    taps = [(k * step_h, "DHWcalc", f * step_h, f / 60, t_use)
            for k, f in enumerate(flows[day * spd:(day + 1) * spd]) if f > 0]
    return taps, dict(days=days, step_min=step_min, daily_L=daily, day=day)


def cop(t_supply, p):
    tc, te = t_supply + 5 + 273.15, p["T_source"] - 5 + 273.15
    return p["eta_carnot"] * tc / max(tc - te, 1.0)


def simulate(p=DEFAULTS, hours=ALL_HOURS, profile=PROFILE):
    n = int(p["n_layers"])
    m_layer = p["V_tank"] / 1000 * RHO / n                   # kg per layer
    dz = p["H_tank"] / n
    area = p["V_tank"] / 1000 / p["H_tank"]
    g_cond = p["k_eff"] * area / dz                           # W/K between layers
    ua_layer = p["UA"] / n
    # layer index counted from the top: height fraction h -> index
    k_in = min(n - 1, max(0, int(n * (1 - p["inlet_pos"] / 100))))
    k_s = min(n - 1, max(0, int(n * (1 - p["sensor_pos"] / 100))))
    T = [p["T_set"]] * n
    on = False
    steps = int(p["days"] * 24 * 3600 / DT)
    rep0 = int((p["days"] - 1) * 24 * 3600 / DT)
    out = dict(t=[], layers=[], t_tap=[], t_use=[], q_tap=[], q_hp=[], t_ch=[], cop=[])
    s = dict(tapped_kWh=0.0, unmet_kWh=0.0, unmet_min=0.0, hp_kWh=0.0, el_kWh=0.0,
             loss_kWh=0.0, starts=0, run_h=0.0)
    for step in range(steps):
        t = step * DT / 3600
        hour = int(t % 24)
        # control
        if not hours[hour]:
            on = False
        elif not on and T[k_s] < p["T_set"] - p["hyst"]:
            on = True
            if step >= rep0:
                s["starts"] += 1
        elif on and (T[k_s] >= p["T_set"] or T[-1] >= p["T_hp_max"] - p["hex_approach"] - 1):
            on = False   # setpoint reached, or high-temperature cut-out: the return is too warm
        # heat pump and heat exchanger
        m_ch, t_ch, q_hp, c = 0.0, float("nan"), 0.0, float("nan")
        if on:
            m_ch = p["flow_ch"] / 60 / 1000 * RHO                # kg/s
            t_bot = T[-1]
            q_max = m_ch * CP * (p["T_hp_max"] - p["hex_approach"] - t_bot)
            q_hp = max(0.0, min(p["P_hp"] * 1000, q_max))
            t_ch = t_bot + q_hp / (m_ch * CP)
            c = cop(t_ch + p["hex_approach"], p)
        # tapping: thermostatic mixer at the tap
        flow, t_use = tap_demand(t % 24, p, profile)
        m_tap, t_tap, q_tap, q_unmet = 0.0, float("nan"), 0.0, 0.0
        if flow > 0:
            m_mix = flow / 1000 * RHO
            if T[0] > t_use:
                frac = (t_use - p["T_cold"]) / (T[0] - p["T_cold"])
                t_tap = t_use
            else:
                frac, t_tap = 1.0, T[0]
            m_tap = m_mix * frac
            q_tap = m_mix * CP * (t_tap - p["T_cold"])
            q_unmet = m_mix * CP * (t_use - t_tap)
        # energy balance per layer: dT_i = dt/m * sum(inflow * (T_in - T_i)) + conduction + loss
        dT = [0.0] * n
        for i in range(n - 1):                                  # interface between i and i+1
            f_up = m_tap - (m_ch if i >= k_in else 0.0)
            if f_up > 0:
                dT[i] += f_up * CP * (T[i + 1] - T[i])
            elif f_up < 0:
                dT[i + 1] += -f_up * CP * (T[i] - T[i + 1])
            q = g_cond * (T[i + 1] - T[i])
            dT[i] += q
            dT[i + 1] -= q
        dT[-1] += m_tap * CP * (p["T_cold"] - T[-1])
        dT[k_in] += m_ch * CP * ((t_ch if on else T[k_in]) - T[k_in])
        loss = 0.0
        for i in range(n):
            ql = ua_layer * (T[i] - p["T_room"])
            loss += ql
            T[i] += DT * (dT[i] - ql) / (m_layer * CP)
        # buoyancy: mix unstable pairs until the tank is stable
        mixed = True
        while mixed:
            mixed = False
            for i in range(n - 1):
                if T[i + 1] > T[i] + 1e-9:
                    j = i + 1
                    while j + 1 < n and T[j + 1] > T[i]:
                        j += 1
                    avg = sum(T[i:j + 1]) / (j + 1 - i)
                    for k in range(i, j + 1):
                        T[k] = avg
                    mixed = True
        if step == rep0 - 1:
            e_start = sum(T) * m_layer * CP / 3.6e6
        if step >= rep0:
            h = DT / 3600 / 1000
            s["tapped_kWh"] += q_tap * h
            s["unmet_kWh"] += q_unmet * h
            if q_unmet > 1e-6 and t_tap < t_use - 1:
                s["unmet_min"] += DT / 60
            s["hp_kWh"] += q_hp * h
            if on and q_hp > 0:
                s["el_kWh"] += q_hp / c * h
                s["run_h"] += DT / 3600
            s["loss_kWh"] += loss * h
            if (step - rep0) % 6 == 0:                          # store every minute
                out["t"].append(t - (p["days"] - 1) * 24)
                out["layers"].append(list(T))
                out["t_tap"].append(t_tap if flow > 0 else float("nan"))
                out["t_use"].append(t_use if flow > 0 else float("nan"))
                out["q_tap"].append(q_tap / 1000)
                out["q_hp"].append(q_hp / 1000)
                out["t_ch"].append(t_ch)
                out["cop"].append(c)
    s["cop_mean"] = s["hp_kWh"] / s["el_kWh"] if s["el_kWh"] > 0 else float("nan")
    s["T_top_end"], s["T_bot_end"] = T[0], T[-1]
    s["stored_change_kWh"] = sum(T) * m_layer * CP / 3.6e6 - e_start   # closes the balance: hp = tapped + loss + change
    out["summary"] = s
    return out


