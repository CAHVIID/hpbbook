function profileHeat(prof, p) {
  const hourly = Array(24).fill(0);
  let vol = 0;
  for (const [t, , v, , tu] of prof) { const q = v * RHO / 1000 * CP * (tu - p.T_cold) / 3.6e6; hourly[Math.floor(t)] += q; vol += v; }
  return { hourly, vol, q: hourly.reduce((a, b) => a + b, 0) };
}

