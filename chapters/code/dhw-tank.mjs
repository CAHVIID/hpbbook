const DT = 10, RHO = 994, CP = 4182;

function tapDemand(tDay, p, profile) {
  // mean flow over the step starting at tDay; only the part of a tapping inside the step counts.
  // Tappings that share a step are added, with a flow-weighted use temperature.
  const stepH = DT / 3600;
  let fSum = 0, ftSum = 0;
  for (const [start, , vol0, flow, temp] of profile) {
    const vol = vol0 * (p.use_scale / 100), end = start + vol / flow / 60;
    const overlap = Math.min(tDay + stepH, end) - Math.max(tDay, start);
    if (overlap > 0) { const f = flow / 60 * overlap / stepH; fSum += f; ftSum += f * temp; }
  }
  return fSum > 0 ? [fSum, ftSum / fSum] : [0, null];
}

// DHWcalc output: a text file with one value per line, the draw-off flow in L/h for each time step,
// for a whole year (365 or 366 days) or a single day. The time step follows from the number of lines.
export function parseDhwcalc(text) {
  const flows = [];
  for (const line of text.split(/\r?\n/)) {
    const t = line.trim(); if (!t) continue;
    const v = Number(t.split(/[\s;]+/).pop().replace(",", "."));
    if (Number.isFinite(v)) flows.push(Math.max(0, v));
  }
  const n = flows.length;
  for (const days of [365, 366, 1]) {
    if (n % days) continue;
    const spd = n / days, stepMin = 1440 / spd;
    if (Number.isInteger(stepMin) || Math.abs(stepMin - Math.round(stepMin)) < 1e-9) {
      const dailyL = [];
      for (let d = 0; d < days; d++) { let s = 0; for (let k = 0; k < spd; k++) s += flows[d * spd + k]; dailyL.push(s * stepMin / 60); }
      return { flows, days, spd, stepMin: Math.round(stepMin), dailyL };
    }
  }
  throw new Error(`Found ${n} values. A DHWcalc file has one flow value (L/h) per time step for 365 days (for example 525 600 lines at 1 min or 8 760 at 60 min) or for one day.`);
}

export function dhwcalcDay(data, day, tUse) {
  // one tapping per time step with flow; the volume is the flow (L/h) times the step length
  const taps = [], stepH = data.stepMin / 60;
  for (let k = 0; k < data.spd; k++) {
    const f = data.flows[day * data.spd + k];
    if (f > 0) taps.push([k * stepH, "DHWcalc", f * stepH, f / 60, tUse]);
  }
  return taps;
}

function cop(tSupply, p) {
  const tc = tSupply + 5 + 273.15, te = p.T_source - 5 + 273.15;
  return p.eta_carnot * tc / Math.max(tc - te, 1);
}

